const GOOD = 'good';
const GOODND = 'goodND';
const R90 = 'r90';
const BAD = 'bad';
const NC = 'nc';
const YES = T[158];
const NO = T[159];

// О8 «Чёрный экран» и «Картинки нет» (TXT-CAP-73) — картинка невидима.
const INVISIBLE = T[73].split(' / ').slice(1).map(lowerFirst);

function rBad() { return { state: BAD, reason: null, best: BAD }; }
function rOk(state) { return { state: state, reason: null, best: state }; }
// q — решающие вопросы без ответа при причине «нет ответа на вопрос» (для набора причин, Д-22).
function rNc(reason, best, q) { return { state: NC, reason: reason, best: best || GOOD, q: q || [] }; }

function missing(obj, keys) {
  return keys.filter(function (k) { return obj[k] !== YES && obj[k] !== NO; });
}

function skippedOrNotReached(st) {
  if (st.status === 'skipped') return rNc(333);
  if (st.status === 'notreached') return rNc(334);
  return null;
}

function step2State(s) {
  const st = s.steps[2];
  const exc = deniedThenGranted(s, 2);
  if (st.mark && !exc) return rBad();
  if (!s.env.hasGUM) return rBad();
  if (st.crashed) return rBad();
  if (exc) return rNc(st.status === 'skipped' ? 333 : 359);
  // 7.1, правило 1 и абзац «Шаг 2»: провал шага 2 (О8, О9) проверяется раньше пропуска.
  if (INVISIBLE.indexOf(st.o8) >= 0) return rBad();
  if (st.o9 === NO) return rBad();
  const sk = skippedOrNotReached(st);
  if (sk) return sk;
  if (st.o9 === YES) return rOk(GOOD);
  return rNc(336, null, ['o9']);
}

// Правила 2, 1, 3 для снимка на странице (шаги 3, 5, 6) — в этом порядке.
function pageCommon(s, n, isVideo, step2) {
  const st = s.steps[n];
  const exc = deniedThenGranted(s, n);
  if (st.mark && !exc) return rBad();
  if (!s.env.hasGUM) return rBad();
  if (isVideo && !s.env.hasRecorder) return rBad();
  if (step2.state === BAD) return rBad();
  if (exc) return st.crashed ? rBad() : rNc(st.status === 'skipped' ? 333 : 359);
  const sk = skippedOrNotReached(st);
  if (sk) return sk;
  if (st.crashed) return rBad();
  return null;
}

// Снимок, годный по своим условиям, не проверен, если не проверен шаг 2.
function withStep2(own, step2) {
  if ((own.state === GOOD || own.state === GOODND) && step2.state === NC) return rNc(null, own.state);
  return own;
}

function pagePhotoState(s, step2) {
  const c = pageCommon(s, 3, false, step2);
  if (c) return c;
  const st = s.steps[3];
  if (!(st.photos > 0)) return rNc(335);
  const f = st.file;
  if (!f || f.received !== YES || !withinPhotoLimit(f.bytes)) return rBad();
  if (st.o11 === NO) return rBad();
  if (st.o11 !== YES) return rNc(336, null, ['o11']);
  return withStep2(rOk(GOOD), step2);
}

function o23Self(v) { return v === ans(308) || v === ans(309); }
function o23Real(v) { return v === ans(307) || v === ans(310); }

function pageVideoState(s, n, step2, live) {
  const c = pageCommon(s, n, true, step2);
  if (c) return c;
  const st = s.steps[n];
  if (!(st.attempts > 0)) return rNc(335);
  const f = st.file || { received: NO };
  if (st.recording || f.stopReason === 'button') return rNc(337);
  const limit = STEP_LIMITS[n];
  const c1 = f.received === YES;
  const c2 = f.stopReason === 'limit';
  let c3 = 'unchecked';
  if (c1 && isNum(f.fileSeconds)) c3 = durationCondition3(f.fileSeconds, limit) === YES;
  const c4 = !c1 || withinVideoLimit(f.bytes);
  const c5 = f.playable !== T[165] && st.o13e !== NO;
  const v1235 = !c1 || !c2 || c3 === false || !c5;
  const vOther = !c4 || st.o13s === NO || st.o13p === NO;
  // Уход со страницы во время записи (7.1): при нарушении только условий 1, 2, 3, 5 решает О23.
  if (st.hiddenCount > 0 && v1235 && !vOther) {
    if (o23Self(st.o23)) return rNc(338);
    if (o23Real(st.o23)) return rBad();
    return rNc(336, null, ['o23']);
  }
  if (v1235 || vOther) return rBad();
  const own = c3 === 'unchecked' ? GOODND : GOOD;
  if (st.o13s !== YES || st.o13p !== YES || st.o13e !== YES) return rNc(336, own, missing(st, ['o13s', 'o13p', 'o13e']));
  return withStep2(rOk(own), step2);
}

// Шаги 9 и 10: item — фото или видео шага; kind — 'photo' или 'video'.
function fileShotState(s, n, item, kind, live) {
  const st = s.steps[n];
  const sk = skippedOrNotReached(st);
  if (sk) return sk;
  if (st.crashed) return rBad();
  const f = item.file;
  if (!f) {
    // Правило 4: файл нужного вида не получен. Последним получен файл не того вида — не проверен,
    // что бы ни ответил владелец (Д-21 (г), Д-29). Иначе решает ответ, что открылось:
    // «сам ничего не снял (не выбрал)» — не проверен, «действие не сделано» (Д-21 (б));
    // без ответа — не проверен; прочие ответы — не годен (Д-21 (в)).
    if (item.wrongKind) return rNc(364);
    const a = n === 9 ? item.o16 : item.o17;
    if (a === null || a === undefined) return rNc(340);
    if (a === ans(n === 9 ? 362 : 363)) return rNc(335);
    return rBad();
  }
  // Правило 5: только файл в зачёте судят правила 6–8.
  if (n === 9) {
    if (!o16Given(item)) return rNc(336, null, ['o16']);
    if (item.o16 !== ans(131)) {
      if (item.o22 === NO) return rNc(349);
      if (item.o22 !== YES) return rNc(336, null, ['o22']);
    }
  } else {
    if (item.o22 === NO) return rNc(349);
    if (item.o22 !== YES) return rNc(336, null, ['o22']);
  }
  if (f.received !== YES) return rBad();
  if (kind === 'photo') {
    if (!withinPhotoLimit(f.bytes)) return rBad();
    if (item.o11 === NO) return rBad();
    if (item.o11 !== YES) return rNc(336, null, ['o11']);
    return rOk(GOOD);
  }
  if (!withinVideoLimit(f.bytes)) return rBad();
  if (f.playable === T[165]) return rBad();
  let r90 = false;
  if (isNum(f.fileSeconds)) r90 = !withinVideoLimit(projected90Bytes(f.bytes, f.fileSeconds));
  else if (!(live && (f.durationMethod === null || f.durationMethod === undefined))) return rBad();
  if (item.o13s === NO || item.o13p === NO || item.o13e === NO) return rBad();
  const own = r90 ? R90 : GOOD;
  if (item.o13s !== YES || item.o13p !== YES || item.o13e !== YES) return rNc(336, own, missing(item, ['o13s', 'o13p', 'o13e']));
  return rOk(own);
}

