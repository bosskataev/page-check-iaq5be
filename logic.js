const SHOTS = ['photoPage', 'v60', 'v90', 'phoneVideo', 'phonePhoto', 'galleryPhoto', 'galleryVideo'];

function goodish(x) { return x === GOOD || x === GOODND; }

// Строки Р1, Р2, «Р2 по размеру», Р3 по состояниям снимков (без «не проверен»).
function lineOutcome(m) {
  const pageVideos = goodish(m.v60) && goodish(m.v90);
  if (m.photoPage === GOOD && pageVideos) return m.v60 === GOODND || m.v90 === GOODND ? T[183] : T[167];
  const anyVideo = pageVideos || m.phoneVideo === GOOD || m.galleryVideo === GOOD;
  const anyPhoto = m.photoPage === GOOD || m.phonePhoto === GOOD || m.galleryPhoto === GOOD;
  if (anyVideo && anyPhoto) return T[168];
  if (anyPhoto && (m.phoneVideo === R90 || m.galleryVideo === R90)) return T[184];
  return T[169];
}

function project(st, how) {
  const m = {};
  SHOTS.forEach(function (k) {
    const r = st[k];
    m[k] = r.state !== NC ? r.state : (how === 'best' ? r.best : BAD);
  });
  return m;
}

// Исход и два расчёта (7.2, «Два расчёта»). incomplete: 'a', 'b' или null.
export function outcomeDetails(s) {
  const out = { outcome: null, incomplete: null, best: null, worst: null, states: null };
  if (s.run.failed) { out.outcome = T[170]; return out; }
  const noAccess = accessSteps(s).length === 0;
  if (noAccess && s.env.hasGUM && o5Procedure(s)) { out.outcome = T[186]; return out; }
  const st = shotStates(s);
  out.states = st;
  const actual = {};
  SHOTS.forEach(function (k) { actual[k] = st[k].state; });
  if (actual.photoPage === GOOD && goodish(actual.v60) && goodish(actual.v90)) {
    out.outcome = lineOutcome(actual);
    return out;
  }
  if (noAccess && s.env.hasGUM && anyDenied(s) && (s.o5 === null || s.o5 === undefined)) {
    out.outcome = T[185];
    out.incomplete = 'b';
    return out;
  }
  const best = lineOutcome(project(st, 'best'));
  const worst = lineOutcome(project(st, 'worst'));
  if (best === worst) { out.outcome = best; return out; }
  out.outcome = T[185];
  out.incomplete = 'a';
  out.best = best;
  out.worst = worst;
  return out;
}

export function computeOutcome(s) {
  return outcomeDetails(s).outcome;
}

// Поле «Не проверено (переделать при повторе):» (TXT-CAP-327) — только при «Неполном».
// Порядок причин (7.1, «Шаг не проверен»): «выбран файл не того вида» — раньше «действие не сделано» (Д-29).
const REASON_ORDER = [333, 334, 359, 364, 335, 340, 349, 337, 338, 336];

function firstReason(list) {
  let best = null;
  list.forEach(function (r) {
    if (!r || r.state !== NC || r.reason === null) return;
    if (best === null || REASON_ORDER.indexOf(r.reason) < REASON_ORDER.indexOf(best)) best = r.reason;
  });
  return best;
}

export function notCheckedField(s, d) {
  d = d || outcomeDetails(s);
  if (d.outcome !== T[185]) return DASH;
  const st = d.states || shotStates(s);
  const parts = [];
  if (d.incomplete === 'b') parts.push('шаг 1: ' + T[339]);
  // У шагов 9 и 10 — по причине отдельно на видео и на фото, в порядке блоков отчёта (Д-26).
  const bySteps = [
    ['шаг 2', [st.step2]], ['шаг 3', [st.photoPage]], ['шаг 5', [st.v60]], ['шаг 6', [st.v90]],
    ['шаг 9, ' + V_SHOT.video, [st.phoneVideo]], ['шаг 9, ' + V_SHOT.photo, [st.phonePhoto]],
    ['шаг 10, ' + V_SHOT.photo, [st.galleryPhoto]], ['шаг 10, ' + V_SHOT.video, [st.galleryVideo]]
  ];
  bySteps.forEach(function (x) {
    const r = firstReason(x[1]);
    if (r !== null) parts.push(x[0] + ': ' + T[r]);
  });
  return parts.length ? parts.join('; ') : DASH;
}

