function durationText(f, limit) {
  if (!isNum(f.fileSeconds)) return T[160] + (limit ? ', в пределе шага: ' + T[187] : '');
  const w = wholeSeconds(f.fileSeconds);
  return formatSeconds(f.fileSeconds) + ' с, получена: ' + (f.durationMethod || T[160]) + ', целых секунд: ' + w +
    (limit ? ', в пределе шага: ' + (w <= limit ? YES : NO) : '');
}

// Поля видео; kind: 'page' (шаги 4–8) или 'file' (шаги 9 и 10).
function videoFields(f, kind, limit) {
  const got = !!f && (f.received === YES || f.received === T[198]);
  const hasData = !!f && f.received === YES;
  const out = {};
  out[261] = line(261, fileReceived(f));
  out[264] = line(264, got ? nr(f.type) : DASH);
  if (kind === 'page') {
    out[268] = line(268, f && isNum(f.clockSeconds) ? formatSeconds(f.clockSeconds) : DASH);
    out[269] = line(269, f && f.stopReason ? STOP[f.stopReason] : DASH);
    out[328] = line(328, f && isNum(f.sysSeconds) ? formatSeconds(f.sysSeconds) : DASH);
    out[329] = line(329, f && f.countFrom === 'start' ? T[341] : (f && f.countFrom === 'press' ? T[342] : DASH));
  }
  out[270] = line(270, hasData ? durationText(f, limit) : DASH);
  out[271] = line(271, got ? formatBytes(f.bytes) + ' байт, ' + formatMB(f.bytes) + ' МБ, в пределе 200 МБ: ' + (withinVideoLimit(f.bytes) ? YES : NO) : DASH);
  let per = null;
  if (hasData) per = perMinuteBytes(f.bytes, isNum(f.fileSeconds) ? f.fileSeconds : f.clockSeconds);
  out[272] = line(272, hasData ? (per === null ? T[160] : formatMB(per)) : DASH);
  if (kind === 'file') {
    const p = hasData ? projected90Bytes(f.bytes, f.fileSeconds) : null;
    out[273] = line(273, hasData ? (p === null ? T[160] : 'около ' + formatMB(p) + ' МБ, в пределе 200 МБ: ' + (withinVideoLimit(p) ? YES : NO)) : DASH);
  }
  out[274] = line(274, hasData ? (isNum(f.width) && isNum(f.height) && f.width > 0 ? f.width + ' × ' + f.height : T[160]) : DASH);
  out[275] = line(275, hasData ? nr(f.playable) : DASH);
  out[276] = line(276, hasData ? nr(f.audio) : DASH);
  if (kind === 'page') {
    out[277] = line(277, hasData ? (isNum(f.level) ? String(f.level) : T[160]) : DASH);
    // И24, И25: справочные поля о порциях и заглушении камеры; «—» — сведений нет (страница
    // закрылась, пока шла запись). У записи, брошенной уходом с шага, — числа (раздел 9, пункт 21).
    const known = !!f && isNum(f.chunks);
    out[367] = line(367, known ? String(f.chunks) : DASH);
    let minText = DASH;
    if (known) minText = isNum(f.chunkMinBytes) && isNum(f.chunkMinAt) ? formatKB(f.chunkMinBytes) + ' КБ на ' + f.chunkMinAt + '-й секунде' : T[370];
    out[368] = line(368, minText);
    out[369] = line(369, f && isNum(f.mutes) ? String(f.mutes) : DASH);
  }
  return out;
}

// Поля выводятся в порядке номеров таблицы «Подписи отчёта».
function ordered(map) {
  return Object.keys(map).map(Number).sort(function (a, b) { return a - b; }).map(function (k) { return map[k]; });
}

function wakeText(st, env) {
  if (!env.hasWakeLock) return T[356];
  const w = st.wake;
  if (w && w.state === 'denied') return fill(T[355], [w.name || T[160]]);
  if (w && w.state === 'ok') return T[354];
  return DASH;
}

// О16 «Галерея», «Другое» или «Ничего» при полученном файле — нужен О22 (7.1, правило 5).
function o22Asked9(item) {
  return !!item.file && o16Given(item) && item.o16 !== ans(131);
}

export function o22Shown9(item) {
  return o22Asked9(item);
}

export function buildReport(s) {
  const headers = T[221].split(' · ');
  const env = s.env;
  const run = s.run;
  const steps = s.steps;
  const d = outcomeDetails(s);
  const st = d.states || shotStates(s);
  const out = [T[220]];
  function push(lines) { lines.forEach(function (l) { out.push(l); }); }

  // [Запуск]
  out.push(headers[0]);
  out.push(line(222, orDash(runNumber(run.phone, run.opened))));
  out.push(line(223, (run.startedAt ? formatMsk(run.startedAt) : DASH) + ' МСК'));
  out.push(line(224, orDash(run.phone)));
  out.push(line(225, orDash(V_OPENED[run.opened])));
  out.push(line(226, run.opened === 'browser' || !run.opened ? DASH : answer(run.where, true)));
  out.push(line(227, classifyPlace(env.ua)));
  out.push(line(228, typed(run.model)));
  out.push(line(229, nr(env.model)));
  out.push(line(230, typed(run.os)));
  out.push(line(231, nr(env.system)));
  out.push(line(232, nr(env.browser)));
  out.push(line(233, env.ua || T[160]));
  out.push(line(234, 'окно ' + nr(env.innerWidth) + ' точек, экран ' + nr(env.screenWidth) + ' точек'));
  out.push(line(235, env.secure ? YES : NO));
  out.push(line(236, env.storage ? YES : NO));

  // [Возможности браузера]
  out.push(headers[1]);
  out.push(line(237, env.hasGUM ? T[197] : NO));
  out.push(line(238, env.hasRecorder ? T[197] : NO));
  out.push(line(239, env.supportedTypes && env.supportedTypes.length ? env.supportedTypes.join(', ') : NO));
  out.push(line(240, env.recorderType || env.chosenType || NO));
  out.push(line(352, env.hasWakeLock ? T[197] : NO));

  // [Доступ к камере]
  out.push(headers[2]);
  const s1 = steps[1];
  const requested = !!s1.first;
  const o5Shown = (s.o5Shown || []).length > 0;
  if (requested || o5Shown) {
    let granted = NO;
    if (s1.granted) granted = s.o5 === ans(46) ? T[206] : YES;
    let o5Where = DASH;
    if (s.o5Step) o5Where = String(s.o5Step);
    else if (o5Shown) o5Where = String(s.o5Shown[s.o5Shown.length - 1]);
    push([
      line(241, run.opened === 'browser' ? YES : V_NOT_DELIBERATE),
      line(242, permText(s1.permBefore)),
      line(243, answer(s.o5, o5Shown)),
      line(244, requested ? requestText(s1.first) : DASH),
      line(245, answer(s1.o6, s1.askedFollow)),
      line(246, answer(s1.o7, s1.askedFollow)),
      line(247, String(s.reloads || 0)),
      fill(T[248], [String(s1.retries || 0)]) + ' ' + (s1.last ? requestText(s1.last) : T[215]),
      line(249, requested ? permText(s1.permAfter) : DASH),
      line(250, s1.gallery || T[207]),
      line(251, granted),
      line(326, s1.status === 'skipped' ? YES : NO),
      line(351, o5Where)
    ]);
  } else {
    out.push(s1.status === 'skipped' ? T[161] : T[162]);
  }

  // Блок шага 2–8: отметка камеры, «пропущено», «не проверялось» или поля.
  function pageBlock(n, noAction, body) {
    const x = steps[n];
    if (x.mark) return [markLine(x.mark)];
    // Блок пропущенного шага 2 печатается целиком, если на нём дан ответ О8 или О9 (раздел 5; Д-24).
    if (x.status === 'skipped' && !(n === 2 && (given(x.o8) || given(x.o9)))) return [T[161]];
    if (x.status === 'notreached') return [T[162]];
    if (noAction && !x.crashed) return [T[162]];
    return body();
  }

  // [Камера на странице]
  out.push(headers[3]);
  const s2 = steps[2];
  push(pageBlock(2, false, function () {
    const c = s2.camera || {};
    const facing = c.facing === 'environment' ? T[192] : (c.facing === 'user' ? T[193] : T[160]);
    const res = isNum(c.width) && isNum(c.height)
      ? c.width + ' × ' + c.height + ', кадров в секунду: ' + (isNum(c.fps) ? formatNumber(c.fps) : T[160])
      : T[160];
    return [
      line(252, answer(s2.o8, true)),
      line(253, facing),
      line(254, answer(s2.o9, true)),
      line(255, answer(s2.o10, true)),
      line(256, res),
      line(257, s2.mic === null || s2.mic === undefined ? DASH : (s2.mic ? YES : NO)),
      line(326, s2.status === 'skipped' ? YES : NO)
    ];
  }));

  // [Фото на странице]
  out.push(headers[4]);
  const s3 = steps[3];
  push(pageBlock(3, !(s3.photos > 0), function () {
    const m = photoFields(s3.file);
    m[265] = line(265, answer(s3.o11, !!s3.file));
    m[266] = line(266, answer(s3.o12, s3.photos > 0));
    m[287] = line(287, verdictText(st.photoPage));
    return ordered(m);
  }));

  // [Видео 10 с] [Видео 60 с] [Видео 90 с] [Сворачивание] [Блокировка]
  [4, 5, 6, 7, 8].forEach(function (n, i) {
    out.push(headers[5 + i]);
    const x = steps[n];
    push(pageBlock(n, !(x.attempts > 0), function () {
      const f = x.file;
      const shown = !!f && f.received === YES;
      const m = videoFields(f, 'page', STEP_LIMITS[n] || null);
      m[267] = line(267, String(x.attempts || 0));
      m[281] = line(281, x.crashed ? YES : NO);
      m[282] = line(282, String(x.hiddenCount || 0));
      m[353] = line(353, wakeText(x, env));
      if (n <= 6) {
        m[278] = line(278, answer(x.o13s, shown));
        m[279] = line(279, answer(x.o13p, shown));
        m[280] = line(280, answer(x.o13e, shown));
        m[330] = line(330, x.hiddenCount > 0 ? answer(x.o23, true) : DASH);
      } else {
        m[283] = line(283, orDash(x.onReturnRec));
        m[284] = line(284, orDash(x.onReturnCam));
        m[285] = line(285, answer(x.o14, x.asked14));
        m[286] = line(286, answer(x.o15, shown));
      }
      if (n === 5) m[287] = line(287, verdictText(st.v60));
      if (n === 6) m[287] = line(287, verdictText(st.v90));
      return ordered(m);
    }));
  });

  function fileBlock(n, body) {
    const x = steps[n];
    if (x.status === 'skipped') return [T[161]];
    if (x.status === 'notreached') return [T[162]];
    return body();
  }

  // [Камера телефона — видео] [Камера телефона — фото]
  const s9 = steps[9];
  out.push(headers[10]);
  push(fileBlock(9, function () {
    const it = s9.v;
    const m = videoFields(it.file, 'file', null);
    m[258] = line(258, answer(it.o16, it.asked16));
    m[260] = line(260, o22Asked9(it) ? answer(it.o22, true) : DASH);
    m[278] = line(278, answer(it.o13s, !!it.file));
    m[279] = line(279, answer(it.o13p, !!it.file));
    m[280] = line(280, answer(it.o13e, !!it.file));
    m[287] = line(287, verdictText(st.phoneVideo));
    return ordered(m);
  }));
  out.push(headers[11]);
  push(fileBlock(9, function () {
    const it = s9.p;
    const m = photoFields(it.file);
    m[258] = line(258, answer(it.o16, it.asked16));
    m[260] = line(260, o22Asked9(it) ? answer(it.o22, true) : DASH);
    m[265] = line(265, answer(it.o11, !!it.file));
    m[287] = line(287, verdictText(st.phonePhoto));
    return ordered(m);
  }));

  // [Галерея — фото] [Галерея — видео]
  const s10 = steps[10];
  out.push(headers[12]);
  push(fileBlock(10, function () {
    const it = s10.p;
    const m = photoFields(it.file);
    m[259] = line(259, answer(it.o17, it.asked17));
    m[260] = line(260, it.file ? answer(it.o22, true) : DASH);
    m[265] = line(265, answer(it.o11, !!it.file));
    m[287] = line(287, verdictText(st.galleryPhoto));
    return ordered(m);
  }));
  out.push(headers[13]);
  push(fileBlock(10, function () {
    const it = s10.v;
    const m = videoFields(it.file, 'file', null);
    m[259] = line(259, answer(it.o17, it.asked17));
    m[260] = line(260, it.file ? answer(it.o22, true) : DASH);
    m[278] = line(278, answer(it.o13s, !!it.file));
    m[279] = line(279, answer(it.o13p, !!it.file));
    m[280] = line(280, answer(it.o13e, !!it.file));
    m[287] = line(287, verdictText(st.galleryVideo));
    return ordered(m);
  }));

  // [Предложение снять камерой телефона]
  out.push(headers[14]);
  out.push(line(288, s.offer && s.offer.shown ? YES : NO));
  out.push(line(289, s.offer && s.offer.reasons && s.offer.reasons.length ? s.offer.reasons.join(', ') : DASH));

  // [Итог]
  out.push(headers[15]);
  const skipped = [];
  for (let n = 1; n <= 10; n++) if (steps[n].status === 'skipped') skipped.push(n);
  out.push(line(290, skipped.length ? skipped.join(', ') : NO));
  out.push(line(291, answer(s.final.o18, true)));
  const crashes = s.crashes || [];
  out.push(line(292, crashes.length
    ? crashes.length + ' раз, незаконченный шаг: ' + crashes.map(function (n) { return stepTitle(n, run.opened); }).join(', ')
    : NO));
  out.push(line(293, String(s.reloads || 0)));
  out.push(line(294, s.errors && s.errors.length ? s.errors.map(oneLine).join('; ') : NO));
  out.push(line(295, typed(s.final.quality)));
  out.push(line(296, typed(s.final.note)));
  out.push(line(297, run.failed ? (oneLine(run.failedReason || '') || DASH) : DASH));
  out.push(line(298, d.outcome));
  out.push(line(327, notCheckedField(s, d)));
  out.push(line(346, anyDenied(s) ? YES : NO));
  out.push(line(357, d.incomplete === 'a' ? d.best : DASH));
  out.push(line(358, d.incomplete === 'a' ? d.worst : DASH));
  const acc = accessSteps(s);
  out.push(line(361, acc.length ? acc.join(', ') : NO));
  return out.join('\n');
}
