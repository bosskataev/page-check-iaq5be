export function parseUserAgent(ua) {
  ua = ua || '';
  let system = null;
  let model = null;
  let browser = null;
  let m = ua.match(/(?:iPhone|CPU) OS (\d+(?:_\d+)*)/);
  if (m && /iPhone|iPad|iPod/.test(ua)) system = 'iOS ' + m[1].replace(/_/g, '.');
  m = ua.match(/Android (\d+(?:\.\d+)*)/);
  if (m) {
    system = 'Android ' + m[1];
    const inner = ua.match(/\(([^)]*)\)/);
    if (inner) {
      const parts = inner[1].split(';').map(function (p) { return p.trim(); });
      for (let i = 0; i < parts.length; i++) {
        const p = parts[i];
        if (!p || p === 'K' || p === 'Linux' || p === 'U' || p === 'Mobile' || p === 'Tablet' || p === 'wv' ||
            /^Android/.test(p) || /^rv:/.test(p) || /^[a-z]{2}(-[A-Za-z]{2})?$/.test(p)) continue;
        model = p.replace(/\s*Build\/.*$/, '');
        break;
      }
    }
  }
  const order = [
    [/YaBrowser\/([\d.]+)/, 'YaBrowser'], [/SamsungBrowser\/([\d.]+)/, 'SamsungBrowser'], [/CriOS\/([\d.]+)/, 'CriOS'],
    [/FxiOS\/([\d.]+)/, 'FxiOS'], [/EdgA?\/([\d.]+)/, 'Edge'], [/OPR\/([\d.]+)/, 'Opera'], [/Firefox\/([\d.]+)/, 'Firefox'],
    [/Chrome\/([\d.]+)/, 'Chrome']
  ];
  for (let i = 0; i < order.length && !browser; i++) {
    m = ua.match(order[i][0]);
    if (m) browser = order[i][1] + ' ' + m[1];
  }
  if (!browser) {
    m = ua.match(/Version\/([\d.]+)/);
    if (m && ua.indexOf('Safari/') >= 0) browser = 'Safari ' + m[1];
  }
  return { system: system, model: model, browser: browser };
}

// Chrome: только getHighEntropyValues(['model','platformVersion','fullVersionList']).
export function describeUaData(platform, high) {
  high = high || {};
  const system = platform && high.platformVersion ? platform + ' ' + high.platformVersion : null;
  const model = high.model ? high.model : null;
  let browser = null;
  const list = high.fullVersionList || [];
  let chromium = null;
  for (let i = 0; i < list.length; i++) {
    const b = list[i];
    if (!b || !b.brand || /not.?a.?brand/i.test(b.brand)) continue;
    if (b.brand === 'Chromium') { chromium = b; continue; }
    if (!browser) browser = b.brand + ' ' + b.version;
  }
  if (!browser && chromium) browser = chromium.brand + ' ' + chromium.version;
  return { system: system, model: model, browser: browser };
}

