// Годность (7.1). Состояния: good, goodND (видео на странице без длительности по файлу),
// r90 («нет, только по пересчёту на 90 секунд»), bad, nc (не проверен).
// У непроверенного — причина (номер текста для поля TXT-CAP-327; null — только из-за шага 2)
// и лучшее состояние, которого он ещё может достичь (7.2, «Два расчёта»).
